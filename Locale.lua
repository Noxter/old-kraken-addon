local language = 'ukUA'
local labelTables = {}

function OldKraken.Translate(text)
    if language == 'enUS' then return english[text] or text end
    return text
end

function OldKraken.GetLanguage()
    return language
end

-- Module-level labels are built before SavedVariables are available.
function OldKraken.LocalizeTable(labels, field)
    labelTables[#labelTables + 1] = {labels = labels, field = field}
end

function OldKraken.InitializeLocale(db)
    local settings = db and db.settings
    language = type(settings) == 'table' and settings.language == 'enUS' and 'enUS' or 'ukUA'
    for _, entry in ipairs(labelTables) do
        for key, value in pairs(entry.labels) do
            if entry.field then
                value[entry.field] = OldKraken.Translate(value[entry.field])
            elseif type(value) == 'string' then
                entry.labels[key] = OldKraken.Translate(value)
            end
        end
    end
    labelTables = {}
end
